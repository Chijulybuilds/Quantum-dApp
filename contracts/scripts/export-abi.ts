/**
 * export-abi.ts - writes the ABIs the server and the app need as typed TypeScript constants
 * (viem/wagmi infer every function and event type from `as const`), and the creation bytecode of
 * Conclave and ConclaveProxy for the server, so deploying needs no Foundry install.
 *
 *   forge build && npm run export-abi
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
type Artifact = { abi: { type: string }[]; bytecode: { object: string } };
const artifact = (file: string, name: string) =>
  JSON.parse(readFileSync(resolve(here, `../out/${file}/${name}.json`), "utf8")) as Artifact;

const conclave = artifact("Conclave.sol", "Conclave");
const proxy = artifact("ConclaveProxy.sol", "ConclaveProxy");
const proxyAdmin = artifact("ProxyAdmin.sol", "ProxyAdmin");
const header = "// Generated by contracts/scripts/export-abi.ts from the Foundry artifacts. Do not edit.\n";

const abis =
  header +
  `export const conclaveAbi = ${JSON.stringify(conclave.abi, null, 2)} as const;\n\n` +
  "/** OpenZeppelin ProxyAdmin: upgrades go through `upgradeAndCall`, owned by Conclave itself. */\n" +
  `export const proxyAdminAbi = ${JSON.stringify(proxyAdmin.abi, null, 2)} as const;\n`;
for (const target of ["../../server/src/abi.ts", "../../app/src/lib/abi.ts"]) {
  writeFileSync(resolve(here, target), abis);
  console.log(`wrote ${resolve(here, target)}`);
}

const bytecode =
  header +
  "// Creation bytecode (solc 0.8.28, via-IR, 1000 runs, Cancun).\n\n" +
  "/** Conclave implementation: deployed once per version, never used directly. */\n" +
  `export const conclaveBytecode = "${conclave.bytecode.object}" as const;\n\n` +
  "/** ConclaveProxy (OpenZeppelin TransparentUpgradeableProxy): the address everyone uses. */\n" +
  `export const conclaveProxyAbi = ${JSON.stringify(proxy.abi.filter((e) => e.type === "constructor"), null, 2)} as const;\n` +
  `export const conclaveProxyBytecode = "${proxy.bytecode.object}" as const;\n`;
writeFileSync(resolve(here, "../../server/src/bytecode.ts"), bytecode);
console.log(`wrote ${resolve(here, "../../server/src/bytecode.ts")}`);
