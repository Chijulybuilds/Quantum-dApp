/**
 * export-abi.ts - writes Conclave's ABI as a typed TypeScript constant for the server and the
 * app (viem/wagmi infer every function and event type from `as const`), and the creation
 * bytecode for the server, so deploying needs no Foundry install.
 *
 *   forge build && npm run export-abi
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = JSON.parse(readFileSync(resolve(here, "../out/Conclave.sol/Conclave.json"), "utf8")) as {
  abi: unknown[];
  bytecode: { object: string };
};
const source =
  "// Generated by contracts/scripts/export-abi.ts from the Foundry artifact. Do not edit.\n" +
  `export const conclaveAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;

for (const target of ["../../server/src/abi.ts", "../../app/src/lib/abi.ts"]) {
  writeFileSync(resolve(here, target), source);
  console.log(`wrote ${resolve(here, target)}`);
}

const bytecode =
  "// Generated by contracts/scripts/export-abi.ts from the Foundry artifact. Do not edit.\n" +
  "// Creation bytecode of Conclave.sol (solc 0.8.28, via-IR, 1000 runs, Cancun).\n" +
  `export const conclaveBytecode = "${artifact.bytecode.object}" as const;\n`;
writeFileSync(resolve(here, "../../server/src/bytecode.ts"), bytecode);
console.log(`wrote ${resolve(here, "../../server/src/bytecode.ts")}`);
